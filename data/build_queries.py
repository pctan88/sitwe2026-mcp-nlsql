def q(
    qid: str,
    question: str,
    gold_pre: str,
    gold_post: str | None,
    perturbation: str,
    touches: list[str],
    expected_failure: bool = False,
    failure_reason: str | None = None,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": qid,
        "question": question,
        "gold_pre": gold_pre,
        "gold_post": gold_post,
        "perturbation": perturbation,
        "touches": touches,
    }
    if expected_failure:
        payload["expected_failure"] = True
        payload["failure_reason"] = failure_reason or f"unanswerable_after_{perturbation}"
    return payload


